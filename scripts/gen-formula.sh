#!/usr/bin/env bash
# Emit a Homebrew formula for CapyScheme on stdout.
#
#   gen-formula.sh <stable|nightly> <version> <assets-dir>
#
# <assets-dir> holds capyscheme-<label>-<target>.tar.gz for every target; the
# sha256 of each is computed here. <version> is the tag without `v` (stable)
# or e.g. 3.0.0-nightly.20261018 (nightly).
set -euo pipefail

kind=${1:?kind: stable|nightly}
version=${2:?version}
assets=${3:?assets dir}
repo=${GITHUB_REPOSITORY:-playX18/capyscheme}

case "$kind" in
  stable)
    class=Capyscheme
    label=$version
    tag="v$version"
    suffix=""
    desc="R6RS/R7RS Scheme compiler and runtime"
    ;;
  nightly)
    class=CapyschemeNightly
    label=nightly
    tag=nightly
    suffix="-nightly"
    desc="R6RS/R7RS Scheme compiler and runtime (nightly build)"
    ;;
  *) echo "unknown kind: $kind" >&2; exit 2 ;;
esac

sha() {
  local f="$assets/capyscheme-$label-$1.tar.gz"
  [ -f "$f" ] || { echo "missing $f" >&2; exit 1; }
  if command -v sha256sum >/dev/null; then sha256sum "$f"; else shasum -a 256 "$f"; fi | cut -d' ' -f1
}
url() { echo "https://github.com/$repo/releases/download/$tag/capyscheme-$label-$1.tar.gz"; }

mac_arm=aarch64-apple-darwin
lin_x64=x86_64-unknown-linux-gnu
lin_arm=aarch64-unknown-linux-gnu

cat <<RUBY
# Generated by scripts/gen-formula.sh in $repo. Do not edit by hand.
class $class < Formula
  desc "$desc"
  homepage "https://github.com/$repo"
  version "$version"
  license "LGPL-3.0-only"

  on_macos do
    on_arm do
      url "$(url $mac_arm)"
      sha256 "$(sha $mac_arm)"
    end
  end

  on_linux do
    on_intel do
      url "$(url $lin_x64)"
      sha256 "$(sha $lin_x64)"
    end
    on_arm do
      url "$(url $lin_arm)"
      sha256 "$(sha $lin_arm)"
    end
  end
RUBY

# The remainder has Ruby interpolation, so keep it in a quoted heredoc.
sed "s/@SUFFIX@/$suffix/g" <<'RUBY'

  def install
    libexec.install Dir["*"]
    # The runtime finds its libraries relative to the real binary, so install
    # wrappers instead of symlinks.
    %w[capy capyc].each do |tool|
      real = Dir[libexec/"*"/tool].first
      odie "#{tool} not found in archive" if real.nil?
      (bin/"#{tool}@SUFFIX@").write <<~SH
        #!/bin/bash
        exec "#{real}" "$@"
      SH
      (bin/"#{tool}@SUFFIX@").chmod 0755
    end
  end

  test do
    capy = bin/"capy@SUFFIX@"

    # Arithmetic, including bignums.
    assert_match "246913578024691357802469135780",
                 shell_output("#{capy} -c '(display (* 123456789012345678901234567890 2))'")

    # Bundled R6RS / SRFI libraries are found through the wrapper.
    assert_match "(2 4 6)",
                 shell_output("#{capy} -c '(import (rnrs) (srfi :1)) (write (map (lambda (x) (* 2 x)) (iota 3 1)))'")
    assert_match "55",
                 shell_output("#{capy} -c '(import (rnrs) (srfi :1)) (display (fold + 0 (iota 11)))'")

    # Running a script file that uses records and string ports.
    (testpath/"hello.scm").write <<~SCHEME
      (import (rnrs))
      (define-record-type point (fields x y))
      (define p (make-point 3 4))
      (display (+ (point-x p) (point-y p)))
      (newline)
      (display (call-with-string-output-port
                 (lambda (port) (put-string port "capy"))))
      (newline)
    SCHEME
    output = shell_output("#{capy} -s #{testpath}/hello.scm")
    assert_match(/^7$/, output)
    assert_match(/^capy$/, output)

    # An uncaught error exits non-zero.
    shell_output("#{capy} -c '(error (quote test) \"boom\")' 2>&1", 1)

    # The compiler driver is installed and executable.
    assert_predicate bin/"capyc@SUFFIX@", :executable?
  end
end
RUBY
