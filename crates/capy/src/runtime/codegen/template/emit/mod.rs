//! One template per opcode, grouped by type.
mod alloc;
mod arith;
pub(crate) mod call;
mod control;
mod entry;
mod memory;
mod moves;
mod primitives;
mod rest;
mod slots;
mod stores;
mod traps;

use super::super::masm::Masm;
use super::TemplateContext;
use crate::bytecode::def::OpcodeId;

/// Emit the template for `op`. Every opcode has one: the match is exhaustive.
pub fn emit_template<C: TemplateContext>(masm: &mut Masm, context: &mut C, op: OpcodeId) {
    match op {
        OpcodeId::OpNop => entry::op_nop(masm, context),
        OpcodeId::OpEnter => entry::op_enter(masm, context),
        OpcodeId::OpEnterRest => entry::op_enter_rest(masm, context),
        OpcodeId::OpReturnPoint => call::op_return_point(masm, context),
        OpcodeId::OpReturnPointForward => call::op_return_point_forward(masm, context),
        OpcodeId::OpReturnPointValues => call::op_return_point_values(masm, context),
        OpcodeId::OpReturnPointValuesRest => call::op_return_point_values_rest(masm, context),
        OpcodeId::OpMove => moves::op_move(masm, context),
        OpcodeId::OpLoadConstant => moves::op_load_constant(masm, context),
        OpcodeId::OpLoadImmediate => moves::op_load_immediate(masm, context),
        OpcodeId::OpLoadRaw => moves::op_load_raw(masm, context),
        OpcodeId::OpCellRef => moves::op_cell_ref(masm, context),
        OpcodeId::OpCellSet => stores::op_cell_set(masm, context),
        OpcodeId::OpRuntimeProcedure => traps::op_runtime_procedure(masm, context),
        OpcodeId::OpClosure => alloc::op_closure(masm, context),
        OpcodeId::OpClosureEnv => alloc::op_closure_env(masm, context),
        OpcodeId::OpFreeRef => moves::op_free_ref(masm, context),
        OpcodeId::OpClosureRef => moves::op_closure_ref(masm, context),
        OpcodeId::OpClosureSet => stores::op_closure_set(masm, context),
        OpcodeId::OpMakeEnv => alloc::op_make_env(masm, context),
        OpcodeId::OpEnvRef => moves::op_env_ref(masm, context),
        OpcodeId::OpEnvSet => stores::op_env_set(masm, context),
        OpcodeId::OpJump => control::op_jump(masm, context),
        OpcodeId::OpJumpIfTrue => control::op_jump_if_true(masm, context),
        OpcodeId::OpJumpIfFalse => control::op_jump_if_false(masm, context),
        OpcodeId::OpJumpIfNull => control::op_jump_if_null(masm, context),
        OpcodeId::OpJumpIfNotNull => control::op_jump_if_not_null(masm, context),
        OpcodeId::OpJumpIfPair => control::op_jump_if_pair(masm, context),
        OpcodeId::OpJumpIfNotPair => control::op_jump_if_not_pair(masm, context),
        OpcodeId::OpJumpIfFixnum => control::op_jump_if_fixnum(masm, context),
        OpcodeId::OpJumpIfNotFixnum => control::op_jump_if_not_fixnum(masm, context),
        OpcodeId::OpJumpIfUndefined => control::op_jump_if_undefined(masm, context),
        OpcodeId::OpJumpIfNotUndefined => control::op_jump_if_not_undefined(masm, context),
        OpcodeId::OpJumpIfEq => control::op_jump_if_eq(masm, context),
        OpcodeId::OpJumpIfNotEq => control::op_jump_if_not_eq(masm, context),
        OpcodeId::OpJumpIfLess => control::op_jump_if_less(masm, context),
        OpcodeId::OpJumpIfLessEqual => control::op_jump_if_less_equal(masm, context),
        OpcodeId::OpJumpIfNumberEqual => control::op_jump_if_number_equal(masm, context),
        OpcodeId::OpJumpIfGreaterEqual => control::op_jump_if_greater_equal(masm, context),
        OpcodeId::OpJumpIfGreater => control::op_jump_if_greater(masm, context),
        OpcodeId::OpJumpIfNotLess => control::op_jump_if_not_less(masm, context),
        OpcodeId::OpJumpIfNotLessEqual => control::op_jump_if_not_less_equal(masm, context),
        OpcodeId::OpJumpIfNotNumberEqual => control::op_jump_if_not_number_equal(masm, context),
        OpcodeId::OpJumpIfNotGreaterEqual => control::op_jump_if_not_greater_equal(masm, context),
        OpcodeId::OpJumpIfNotGreater => control::op_jump_if_not_greater(masm, context),
        OpcodeId::OpSwitchFixnum => control::op_switch_fixnum(masm, context),
        OpcodeId::OpSwitchChar => control::op_switch_char(masm, context),
        OpcodeId::OpSwitchSymbol => control::op_switch_symbol(masm, context),
        OpcodeId::OpLoopHint => control::op_loop_hint(masm, context),
        OpcodeId::OpCall => call::op_call(masm, context),
        OpcodeId::OpTailCall => call::op_tail_call(masm, context),
        OpcodeId::OpCallSelf => call::op_call_self(masm, context),
        OpcodeId::OpTailCallSelf => call::op_tail_call_self(masm, context),
        OpcodeId::OpReturn => call::op_return(masm, context),
        OpcodeId::OpReturnValues => call::op_return_values(masm, context),
        OpcodeId::OpRaise => traps::op_raise(masm, context),
        OpcodeId::OpRestRef => rest::op_rest_ref(masm, context),
        OpcodeId::OpRestLen => rest::op_rest_len(masm, context),
        OpcodeId::OpRestNull => rest::op_rest_null(masm, context),
        OpcodeId::OpRestPair => rest::op_rest_pair(masm, context),
        OpcodeId::OpRestList => alloc::op_rest_list(masm, context),
        OpcodeId::OpValuesRest => alloc::op_values_rest(masm, context),
        OpcodeId::OpCallPrimitive0 => primitives::op_call_primitive0(masm, context),
        OpcodeId::OpCallPrimitive1 => primitives::op_call_primitive1(masm, context),
        OpcodeId::OpCallPrimitive2 => primitives::op_call_primitive2(masm, context),
        OpcodeId::OpCallPrimitive3 => primitives::op_call_primitive3(masm, context),
        OpcodeId::OpCallPrimitiveN => primitives::op_call_primitive_n(masm, context),
        OpcodeId::OpCar => arith::op_car(masm, context),
        OpcodeId::OpCdr => arith::op_cdr(masm, context),
        OpcodeId::OpCons => alloc::op_cons(masm, context),
        OpcodeId::OpSetCar => stores::op_set_car(masm, context),
        OpcodeId::OpSetCdr => stores::op_set_cdr(masm, context),
        OpcodeId::OpEq => arith::op_eq(masm, context),
        OpcodeId::OpNot => arith::op_not(masm, context),
        OpcodeId::OpAdd => arith::op_add(masm, context),
        OpcodeId::OpSub => arith::op_sub(masm, context),
        OpcodeId::OpMul => arith::op_mul(masm, context),
        OpcodeId::OpAddImmediate => arith::op_add_immediate(masm, context),
        OpcodeId::OpLess => arith::op_less(masm, context),
        OpcodeId::OpLessEqual => arith::op_less_equal(masm, context),
        OpcodeId::OpNumberEqual => arith::op_number_equal(masm, context),
        OpcodeId::OpGreaterEqual => arith::op_greater_equal(masm, context),
        OpcodeId::OpGreater => arith::op_greater(masm, context),
        OpcodeId::OpDiv => arith::op_div(masm, context),
        OpcodeId::OpQuotient => arith::op_quotient(masm, context),
        OpcodeId::OpRemainder => arith::op_remainder(masm, context),
        OpcodeId::OpModulo => arith::op_modulo(masm, context),
        OpcodeId::OpNegate => arith::op_negate(masm, context),
        OpcodeId::OpAbs => arith::op_abs(masm, context),
        OpcodeId::OpSqrt => arith::op_sqrt(masm, context),
        OpcodeId::OpVectorRef => arith::op_vector_ref(masm, context),
        OpcodeId::OpVectorSet => stores::op_vector_set(masm, context),
        OpcodeId::OpVectorLength => arith::op_vector_length(masm, context),
        OpcodeId::OpVariableRef => arith::op_variable_ref(masm, context),
        OpcodeId::OpVariableSet => stores::op_variable_set(masm, context),
        OpcodeId::OpGetSlot => slots::op_get_slot(masm, context),
        OpcodeId::OpPutSlot => slots::op_put_slot(masm, context),
        OpcodeId::OpMoveTwo => moves::op_move_two(masm, context),
        OpcodeId::OpAddImmediateMove => arith::op_add_immediate_move(masm, context),
        OpcodeId::OpVectorRefMul => arith::op_vector_ref_mul(masm, context),
    }
}
